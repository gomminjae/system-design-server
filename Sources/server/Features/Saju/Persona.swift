    /// 손님 현재 나이 한 줄 — 시제·나이대 앵커용. 생년 기준 대략(만 나이 근사).
    /// 이게 없으면 모델이 지나간 나이를 미래처럼 예언해 나이 든 손님에게 헛말을 한다.
    static func ageLine(birthYear: Int) -> String {
        let now = Calendar(identifier: .gregorian).component(.year, from: Date())
        return "[이 손님 지금] \(now)년 현재 약 \(now - birthYear)세. (이 나이 기준으로 시제를 맞춰라)"
    }

    /// SajuResult → GPT용 쉬운말 요약. 한자·전문용어는 빼고, 신살 이름만 유지(무당 맛).
    static func text(_ r: SajuResult) -> String {
        let five = ["목", "화", "토", "금", "수"].map { "\(elementName[$0]!) \(r.fiveElements[$0] ?? 0)개" }.joined(separator: ", ")
        let strength: String
        switch r.advanced.dayStrength.strength {
        case "strong": strength = "기운이 강한 편"
        case "weak": strength = "기운이 약한 편"
        default: strength = "기운이 중간"
        }
        func tg(_ p: Analyze.TenGodPair) -> String { "\(tenGod[p.stem] ?? p.stem), \(tenGod[p.branch] ?? p.branch)" }
        let need = Set(r.advanced.yongsin.compactMap { stemElement[$0] }).sorted().joined(separator: "·")
        let daeun = r.daeun.list.prefix(6)
            .map { "\($0.startAge)세부터 \(tenGod[$0.stemTenGod] ?? $0.stemTenGod) 기운" }
            .joined(separator: " → ")
        // 신살 (뜻 포함) — 콕 집을 재료
        let allSals = Array(Set(
            [r.sals.year, r.sals.month, r.sals.day, r.sals.hour].flatMap { $0.specialSals }
                + r.advanced.sinsal.gilsin + r.advanced.sinsal.hyungsin
        )).sorted()
        let salsLine = allSals.isEmpty ? "특이한 살 없음"
            : allSals.map { s in salMeaning[s].map { "\(s) = \($0)" } ?? s }.joined(separator: " / ")

        // 특이점 — 결핍 오행·극단 (여기가 '콕 집는' 핵심)
        let missing = ["목", "화", "토", "금", "수"].filter { (r.fiveElements[$0] ?? 0) == 0 }.map { elementName[$0]! }
        let over = ["목", "화", "토", "금", "수"].filter { (r.fiveElements[$0] ?? 0) >= 3 }.map { elementName[$0]! }
        var quirks: [String] = []
        if !missing.isEmpty { quirks.append("아예 없는 기운: \(missing.joined(separator: "·")) → 이쪽이 결핍·약점(성격/삶에서 이게 부족해 생기는 문제를 콕 짚어라)") }
        if !over.isEmpty { quirks.append("과하게 많은 기운: \(over.joined(separator: "·")) → 이게 넘쳐서 생기는 성향/문제를 짚어라") }
        if r.advanced.dayStrength.score >= 90 { quirks.append("기운이 극단적으로 강함 → 고집·독단·안 굽힘") }
        if r.advanced.dayStrength.score <= 25 { quirks.append("기운이 아주 약함 → 휘둘림·의존·자기 확신 부족") }
        let quirkLine = quirks.isEmpty ? "특이점 없음" : quirks.joined(separator: " / ")

        return """
        ※ 아래는 쉬운 말로 요약한 것이다. 사주 용어나 한자를 그대로 옮기지 말고, 이 뜻만 네 말투로 풀어라.
        [★ 콕 집을 특이점 (여기를 근거로 구체적으로 짚어라)]
        \(quirkLine)
        [기본] \(strength) (오행: \(five))
        [타고난 성향] 조상/부모 자리[\(tg(r.tenGods.year))], 사회 자리[\(tg(r.tenGods.month))], 본인[\(tg(r.tenGods.day))], 자식/말년 자리[\(tg(r.tenGods.hour))]
        [사주 유형] \(geukguk[r.advanced.geukguk] ?? r.advanced.geukguk)
        [채우면 좋은 기운] \(need.isEmpty ? "없음" : need)
        [타고난 살(신살)] \(salsLine)
        [운의 흐름] \(daeun)
        """
    }

    /// 올해부터 몇 해의 세운 → GPT용 쉬운말 블록. "지금이 어떤지, 언제가 좋은지" 콕 짚는 근거.
    /// 대운(10년)과 달리 해마다 바뀌는 기운이라 결정·시기 예언의 핵심 재료다.
    static func annualText(dayStemIndex: Int, fromYear: Int, count: Int = 3) -> String {
        let lines = (0..<count).map { offset -> String in
            let y = fromYear + offset
            let f = Saju.annualFortune(dayStemIndex: dayStemIndex, calendarYear: y)
            let label = offset == 0 ? "올해" : (offset == 1 ? "내년" : "\(y)년")
            let stem = tenGod[f.stemTenGod] ?? f.stemTenGod
            let branch = tenGod[f.branchTenGod] ?? f.branchTenGod
            return "\(label)(\(f.ganzhiKo)년, \(y)): \(stem) / \(branch)"
        }.joined(separator: "\n")
        return """
        [올해·다가올 해 기운 (세운) — '지금 어떤지, 언제가 좋은지' 콕 짚을 근거]
        \(lines)
        ※ 위 '병오년' 같은 해 이름은 그대로 써도 좋으나, 십성 뜻은 네 말투로 풀어라. 이 흐름으로 시기를 예언해라.
        """
    }
